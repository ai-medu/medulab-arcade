EXAMPLE_NAME = '올로AI 2단계 코딩'


def _q(question, choices, answer, explain):
    return {'q': question, 'choices': choices, 'answer': answer, 'explain': explain}


def _missions(basic, apply, challenge):
    rows = (basic, apply, challenge)
    return [{'id': f'm{n}', 'stars': n, 'title': r[0], 'desc': r[1], 'hint': r[2] if len(r) > 2 else ''} for n, r in enumerate(rows, 1)]


def _how(number):
    """2단계 통합 예제에서 로봇을 고르는 방법 (조종기 숫자 버튼을 누를 때마다 그 수가 더해지고, U 로 시작)."""
    presses = f'{number}번' if number <= 6 else f'6번, 이어서 {number - 6}번'
    return f'로봇에 내려받아 실행한 뒤, 조종기에서 숫자 버튼 {presses}을 누르고 U 버튼을 누르면 이 로봇의 동작이 시작돼요. (D 버튼은 다시 고르기)'


def _code(number, title, intro, steps, drive=True, note=''):
    code = {'start': number, 'title': title, 'intro': intro, 'steps': steps, 'drive': drive,
            'example': EXAMPLE_NAME, 'how': _how(number)}
    if note:
        code['note'] = note
    return code


